import pandas as pd

print("=== pandas 기초: 고객 주문 데이터 분석 실습 ===")

# 1. 딕셔너리 기반으로 DataFrame 생성
data = {
    "주문번호": ["ORD-001", "ORD-002", "ORD-003", "ORD-004", "ORD-005"],
    "고객명": ["김철수", "이영희", "박민수", "최수진", "정지원"],
    "상품카테고리": ["전자기기", "도서", "도서", "패션", "식품"],
    "주문금액": [125000, 28000, 45000, 89000, 34000],
    "배송비": [3000, 0, 0, 3000, 2500]
}
df = pd.DataFrame(data)

# 2. 데이터 기본 구조 및 통계 확인
print("\n[ 1. 전체 데이터프레임 확인 ]")
print(df)

print("\n[ 2. 주문금액 기초 통계 요약 (describe) ]")
print(df["주문금액"].describe().round(1))

# 3. 새로운 열(Column) 파생 계산 : '총결제금액' = 주문금액 + 배송비
df["총결제금액"] = df["주문금액"] + df["배송비"]

# 4. 조건 검색 (Boolean Indexing): 결제금액이 10만원 이상 주문만 필터링
vip_orders = df[df["총결제금액"] >= 100000]
print(vip_orders[["주문번호", "고객명", "총결제금액"]])

# 5. 카테고리별 주문 건수 세기 (value_count)
print("\n[ 4. 카테고리별 주문 건수]")
print(df["상품카테고리"].value_counts())

